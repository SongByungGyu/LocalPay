def lookup_market(market_name: Optional[str]) -> Optional[tuple[float, float, str]]:
    """소속 시장명 → (lat, lng, district). 매핑 실패 시 None."""
    if not market_name:
        return None
    return ANYANG_MARKET_COORDS.get(market_name.strip())


def all_markets() -> list[str]:
    return list(ANYANG_MARKET_COORDS.keys())
